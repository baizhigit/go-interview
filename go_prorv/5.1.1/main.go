package main

import "fmt"

// Задача: Слияние двух отсортированных массивов
//
// Даны два отсортированных массива arr1 и arr2.
// Массив arr1 содержит m отсортированных элементов, за которыми идут n нулей.
// Массив arr2 содержит n отсортированных элементов.
// Нужно смержить два массива и сохранить результат внутри массива arr1.
//
// Требования:
// - Результат должен быть отсортирован по неубыванию
// - Изменения должны быть сделаны in-place в arr1
// - Не использовать дополнительный массив (кроме O(1) памяти)
//
// Примеры:
// Input: arr1=[1,3,5,7,0,0,0,0], m=4, arr2=[2,4,6,8], n=4
// Output: arr1=[1,2,3,4,5,6,7,8]
//
// Input: arr1=[1,2,3,0,0,0], m=3, arr2=[2,5,6], n=3
// Output: arr1=[1,2,2,3,5,6]
//
// Input: arr1=[0], m=0, arr2=[1], n=1
// Output: arr1=[1]

func merge(arr1 []int, m int, arr2 []int, n int) {
	i := m - 1
	j := n - 1
	k := m + n - 1

	for i >= 0 && j >= 0 {
		if arr1[i] > arr2[j] {
			arr1[k] = arr1[i]
			i--
		} else {
			arr1[k] = arr2[j]
			j--
		}
		k--
	}

	for j >= 0 {
		arr1[k] = arr2[j]
		j--
		k--
	}
}

func main() {
	// Тест 1
	arr1 := []int{1, 3, 5, 7, 0, 0, 0, 0}
	arr2 := []int{2, 4, 6, 8}
	merge(arr1, 4, arr2, 4)
	fmt.Println("Тест 1:", arr1) // Ожидается: [1,2,3,4,5,6,7,8]

	// Тест 2
	arr1 = []int{1, 2, 3, 0, 0, 0}
	arr2 = []int{2, 5, 6}
	merge(arr1, 3, arr2, 3)
	fmt.Println("Тест 2:", arr1) // Ожидается: [1,2,2,3,5,6]

	// Тест 3
	arr1 = []int{0}
	arr2 = []int{1}
	merge(arr1, 0, arr2, 1)
	fmt.Println("Тест 3:", arr1) // Ожидается: [1]

	// Тест 4
	arr1 = []int{1, 2, 3, 4, 10, 0, 0, 0}
	arr2 = []int{5, 5, 6}
	merge(arr1, 5, arr2, 3)
	fmt.Println("Тест 4:", arr1) // Ожидается: [1,2,3,4,5,5,6,10]
}
